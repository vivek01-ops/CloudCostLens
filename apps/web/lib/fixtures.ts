const now = new Date();

function isoDaysAgo(days: number, h = 0): string {
  const d = new Date(now);
  d.setDate(d.getDate() - days);
  d.setHours(h, 0, 0, 0);
  return d.toISOString();
}

/** Deterministic daily spend for the last 30 days (fixture). */
function trendSeries(days: number, base: number, wobble: number): { date: string; amount: number }[] {
  return Array.from({ length: days }, (_, i) => {
    const idx = days - i;
    const wave = Math.sin(idx / 4) * wobble;
    const weekdayDip = (idx % 7 === 0 || idx % 7 === 6 ? 0.25 : 0) * base;
    return {
      date: isoDaysAgo(idx, 0).slice(0, 10),
      amount: Math.round((base + wave - weekdayDip) * 100) / 100,
    };
  });
}

/** Deterministic utilization series for a resource detail view (fixture). */
export function demoUtilizationSeries(
  cpuAvgPct: number | null | undefined,
  days = 14,
): { date: string; amount: number }[] {
  return Array.from({ length: days }, (_, i) => ({
    date: isoDaysAgo(days - 1 - i, 0).slice(0, 10),
    amount: cpuAvgPct == null ? 0 : Math.max(0, cpuAvgPct + Math.sin(i) * 3),
  }));
}

